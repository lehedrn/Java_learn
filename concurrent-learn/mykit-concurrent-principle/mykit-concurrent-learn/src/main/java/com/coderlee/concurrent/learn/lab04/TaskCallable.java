package com.coderlee.concurrent.learn.lab04;

/**
 * 定义回调接口，用于处理任务执行结果。
 * <p>
 * 该接口的主要目的是为异步任务或并发任务提供一个统一的回调机制。
 * 通过实现该接口，调用方可以在任务完成后对结果数据进行自定义处理。
 * </p>
 */
public interface TaskCallable<T> {

    /**
     * 定义接收任务结果的方法。
     * <p>
     * 该方法会在任务执行完成后被调用，参数 `t` 表示任务的执行结果。
     * 实现类需要在该方法中编写逻辑以处理任务返回的数据。
     * </p>
     *
     * @param t 任务执行结果数据，类型为泛型 T
     * @return 处理后的结果数据，类型为泛型 T
     */
    T callable(T t);
}