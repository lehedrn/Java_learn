package com.coderlee.concurrent.chapter16;

/**
 * CasLock 是一个基于 CAS（Compare-And-Swap）机制的锁接口。
 * <p>
 * 该接口定义了锁的基本操作，包括加锁（{@link #lock()}）和解锁（{@link #unlock()}）。
 * 它的设计意图是为实现无锁或轻量级锁提供统一的抽象，适用于高并发场景下的线程同步。
 * <p>
 * 实现类需要确保锁的获取和释放过程是线程安全的，并且能够避免死锁和竞态条件。
 */
public interface CasLock {

    /**
     * 获取锁。
     * <p>
     * 当前线程尝试获取锁，如果锁已被其他线程持有，则当前线程可能会进入等待状态，
     * 直到锁被释放并成功获取为止。
     */
    void lock();

    /**
     * 释放锁。
     * <p>
     * 当前线程释放持有的锁，允许其他线程获取该锁。
     * 如果当前线程未持有锁，则行为取决于具体实现（可能抛出异常或忽略操作）。
     */
    void unlock();
}